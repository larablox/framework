/**
 * Simple Unicode case mapping.
 *
 * No upstream counterpart: PHP gets this from `mbstring`, and Luau's
 * `string.lower`/`string.upper` fold ASCII only (see
 * `agent_docs/roblox-ts-constraints.md`), so `Str`'s casing helpers were ASCII
 * -only too. This table restores parity with PHP's `mb_strtolower`/
 * `mb_strtoupper`, which apply Unicode *simple* case mapping with no locale.
 *
 * Deliberately not covered, matching what `mb_*` does without a locale:
 *
 * - mappings that change length -- `ß` (U+00DF) uppercases to `SS` in full
 *   case mapping, and stays `ß` here;
 * - locale-specific rules -- Turkish dotless `ı`, Lithuanian accented `i`.
 *
 * The table is generated, not hand-written: for every codepoint, ICU's own
 * `toLowerCase()`/`toUpperCase()` decide the mapping, and the pairs are packed
 * into `[start, stride, count, delta]` runs -- `stride` because whole blocks
 * alternate upper/lower (Latin Extended-A), `delta` because whole blocks share
 * one offset (Cyrillic is +32, like ASCII).
 */

